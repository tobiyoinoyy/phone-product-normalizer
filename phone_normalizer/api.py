# Directory names generated by this project, virtual environments, and common
# source-control folders are pruned while collecting a directory input.  A
# caller can still pass a generated image as an explicit file path.
EXCLUDED_DIRECTORY_NAMES = frozenset(
    {
        ".git",
        ".hg",
        ".svn",
        ".venv",
        "__pycache__",
        "node_modules",
        "build",
        "dist",
        "outputs",
        "结果",
    }
)

